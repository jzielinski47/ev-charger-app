CREATE TABLE car_brand
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(64)  NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE car_model
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id             BIGINT       NOT NULL REFERENCES car_brand (id) ON DELETE CASCADE,
    name                 VARCHAR(100) NOT NULL,
    battery_capacity_kwh DOUBLE PRECISION,
    max_ac_power_kw      DOUBLE PRECISION,
    max_dc_power_kw      DOUBLE PRECISION,
    ac_phases            INTEGER,
    UNIQUE (brand_id, name)
);

CREATE TABLE car_model_inlets
(
    model_id BIGINT       NOT NULL REFERENCES car_model (id) ON DELETE CASCADE,
    inlet    VARCHAR(255) NOT NULL,
    PRIMARY KEY (model_id, inlet)
);

