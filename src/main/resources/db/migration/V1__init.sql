CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    surname       VARCHAR(255) NOT NULL,
    email         VARCHAR(100) NOT NULL UNIQUE,
    password      VARCHAR(255) NOT NULL,
    is_non_locked BOOLEAN,
    created_at    TIMESTAMP(6),
    updated_at    TIMESTAMP(6)
);

CREATE TABLE user_roles
(
    user_id BIGINT       NOT NULL REFERENCES users (id),
    role    VARCHAR(255) NOT NULL,
    PRIMARY KEY (user_id, role)
);

CREATE TABLE vehicle
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id                   BIGINT REFERENCES users (id),
    brand                      VARCHAR(255),
    model                      VARCHAR(255),
    year_of_production         INTEGER,
    vehicle_originating_market VARCHAR(255),
    battery_capacity_kwh       DOUBLE PRECISION,
    max_ac_power_kw            DOUBLE PRECISION,
    max_dc_power_kw            DOUBLE PRECISION,
    ac_phases                  INTEGER
);

CREATE TABLE vehicle_connector_types
(
    vehicle_id     BIGINT NOT NULL REFERENCES vehicle (id),
    connector_type VARCHAR(255)
);

CREATE TABLE address_info
(
    id                BIGINT PRIMARY KEY,
    title             VARCHAR(255),
    address_line1     VARCHAR(255),
    address_line2     VARCHAR(255),
    town              VARCHAR(255),
    state_or_province VARCHAR(255),
    postcode          VARCHAR(255),
    location          geometry(Point, 4326),
    access_comments   TEXT
);

CREATE TABLE charger_point
(
    charger_point_id BIGINT PRIMARY KEY,
    address_info_id  BIGINT UNIQUE REFERENCES address_info (id)
);

CREATE TABLE connection
(
    id               BIGINT PRIMARY KEY,
    charger_point_id BIGINT REFERENCES charger_point (charger_point_id),
    amps             INTEGER,
    voltage          INTEGER,
    powerkw          DOUBLE PRECISION,
    quantity         INTEGER,
    connector_type   VARCHAR(255),
    current_type     VARCHAR(255)
);

CREATE INDEX idx_connection_charger_point ON connection (charger_point_id);
CREATE INDEX idx_vehicle_owner ON vehicle (owner_id);
CREATE INDEX idx_vehicle_connector_types_vehicle ON vehicle_connector_types (vehicle_id);